export class CircuitRepository {
  private readonly store = new Map<string, SeasonCircuitMetadata>();

  constructor(initialEntries: SeasonCircuitMetadata[] = [
    ...F1_2026_CALENDAR_METADATA,
    ...HISTORICAL_AND_RESERVE_CIRCUITS,
  ]) {
    for (const entry of initialEntries) {
      // Deep freeze defensive copy so historical seasons are immutable
      this.store.set(this.makeKey(entry.circuitCode, entry.seasonYear), structuredClone(entry));
    }
  }

  private makeKey(circuitCode: string, seasonYear: number): string {
    return `${seasonYear}::${circuitCode}`;
  }

  public getCircuit(circuitCode: string, seasonYear: number = 2026): SeasonCircuitMetadata | undefined {
    const exact = this.store.get(this.makeKey(circuitCode, seasonYear));
    if (exact) return structuredClone(exact);
    // Fallback to latest available season for reserve circuits
    for (const entry of this.store.values()) {
      if (entry.circuitCode === circuitCode) {
        return structuredClone(entry);
      }
    }
    return undefined;
  }

  public getSeasonCalendar(seasonYear: number = 2026): SeasonCircuitMetadata[] {
    const list: SeasonCircuitMetadata[] = [];
    for (const entry of this.store.values()) {
      if (entry.seasonYear === seasonYear && entry.inCalendar) {
        list.push(structuredClone(entry));
      }
    }
    return list.sort((a, b) => a.round - b.round);
  }

  public getAllCircuitsForSeason(seasonYear: number = 2026): SeasonCircuitMetadata[] {
    const byCode = new Map<string, SeasonCircuitMetadata>();
    for (const entry of this.store.values()) {
      if (entry.seasonYear <= seasonYear) {
        const prev = byCode.get(entry.circuitCode);
        if (!prev || entry.seasonYear > prev.seasonYear) {
          byCode.set(entry.circuitCode, structuredClone(entry));
        }
      }
    }
    return Array.from(byCode.values()).sort((a, b) => {
      if (a.inCalendar !== b.inCalendar) return a.inCalendar ? -1 : 1;
      return a.round - b.round;
    });
  }

  public getCircuitVersions(circuitCode: string): SeasonCircuitMetadata[] {
    const versions: SeasonCircuitMetadata[] = [];
    for (const entry of this.store.values()) {
      if (entry.circuitCode === circuitCode) {
        versions.push(structuredClone(entry));
      }
    }
    return versions.sort((a, b) => b.seasonYear - a.seasonYear);
  }

  public upsertSeasonVersion(entry: SeasonCircuitMetadata): void {
    // Only writes to (circuitCode, entry.seasonYear); never overwrites prior seasonYears!
    const key = this.makeKey(entry.circuitCode, entry.seasonYear);
    this.store.set(key, structuredClone(entry));
  }
}

export const defaultCircuitRepository = new CircuitRepository();
